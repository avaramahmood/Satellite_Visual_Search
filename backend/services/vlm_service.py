"""
VLM Service — uses OpenRouter to run Claude-3.5-Sonnet for three tasks:
  1. analyze_satellite_scene   — visual + context-aware scene analysis
  2. generate_evaluation_report — ML metrics report from context JSON
  3. vlm_chat                   — general Q&A grounded in search context
"""
from __future__ import annotations

import base64
import os

from openai import AsyncOpenAI

from services.context_manager import load_search_context, load_metrics

_OPENROUTER_MODEL      = "anthropic/claude-3-haiku"
_OPENROUTER_MAX_TOKENS = 1024


def _get_client() -> AsyncOpenAI:
    api_key = os.getenv("OPENROUTER_API_KEY", "")
    if not api_key:
        raise ValueError("OPENROUTER_API_KEY environment variable is not set.")
    return AsyncOpenAI(
        base_url="https://openrouter.ai/api/v1",
        api_key=api_key,
    )


def _b64(image_bytes: bytes) -> str:
    return base64.b64encode(image_bytes).decode("utf-8")


async def analyze_satellite_scene(
    annotated_map_bytes: bytes,
    reference_chip_bytes: bytes,
    location_name: str,
    target_label: str,
    session_id: str,
) -> str:
    """
    Visual + context-aware analysis combining the annotated map image,
    the reference chip, and the exact k-NN bounding-box data from context JSON.
    """
    if not os.getenv("OPENROUTER_API_KEY"):
        return "VLM analysis unavailable — set OPENROUTER_API_KEY in the backend environment."

    client = _get_client()
    math_context = load_search_context(session_id)

    system_prompt = (
        "You are an expert geospatial intelligence analyst. "
        "I will provide you with a reference image chip, an annotated satellite map, "
        "and a JSON context file containing the exact bounding boxes and confidence "
        "scores generated by our DINOv2 k-NN model."
    )

    user_prompt = (
        f"Target: '{target_label}' at {location_name}.\n\n"
        f"### K-NN MODEL DATA CONTEXT:\n{math_context}\n\n"
        "Tasks:\n"
        "1. Cross-reference the red bounding boxes on the annotated map with the JSON context data.\n"
        "2. Verify if the detected objects visually match the reference chip. "
        "Flag any high-confidence detections that appear to be false positives.\n"
        "3. Provide a concise tactical/intelligence summary of the surrounding area.\n\n"
        "Keep the response structured with clear sections."
    )

    response = await client.chat.completions.create(
        model=_OPENROUTER_MODEL,
        max_tokens=_OPENROUTER_MAX_TOKENS,
        messages=[
            {"role": "system", "content": system_prompt},
            {
                "role": "user",
                "content": [
                    {"type": "text", "text": user_prompt},
                    {
                        "type": "image_url",
                        "image_url": {"url": f"data:image/jpeg;base64,{_b64(reference_chip_bytes)}"},
                    },
                    {
                        "type": "image_url",
                        "image_url": {"url": f"data:image/jpeg;base64,{_b64(annotated_map_bytes)}"},
                    },
                ],
            },
        ],
    )
    return response.choices[0].message.content


async def generate_evaluation_report(
    session_id: str,
    ground_truth_count: int | None = None,
) -> str:
    """
    Generate a rigorous ML evaluation report (Precision@K, mAP, NDCG, etc.)
    derived from the confidence scores in the context JSON.
    Pre-computed metrics are injected so the LLM can validate and narrate them.
    """
    if not os.getenv("OPENROUTER_API_KEY"):
        return "VLM unavailable — set OPENROUTER_API_KEY in the backend environment."

    client = _get_client()
    math_context    = load_search_context(session_id)
    precomputed     = load_metrics(session_id)
    metrics_section = ""
    if precomputed and precomputed.get("metrics"):
        m = precomputed["metrics"]
        metrics_section = f"""
### PRE-COMPUTED METRICS (Python-calculated, use as your ground truth):
| Metric         | Value   |
|----------------|---------|
| Precision@K    | {m.get('precision_at_k', 'N/A')} |
| Recall@K       | {m.get('recall_at_k', 'N/A')} |
| F1-Score       | {m.get('f1', 'N/A')} |
| mAP            | {m.get('map', 'N/A')} |
| NDCG@K         | {m.get('ndcg_at_k', 'N/A')} |
| MRR            | {m.get('mrr', 'N/A')} |
| Silhouette     | {m.get('silhouette', 'N/A')} |
| K (total)      | {m.get('k', 'N/A')} |
| Conf Mean      | {m.get('conf_mean', 'N/A')} |
| Conf Std Dev   | {m.get('conf_std', 'N/A')} |
| High Conf (≥0.75) | {m.get('high_conf_count', 'N/A')} |

Note: {m.get('note', '')}
"""

    system_prompt = (
        "You are a Lead Machine Learning Evaluator specializing in Computer Vision "
        "and Information Retrieval Systems. Your task is to generate a highly "
        "professional, formatted Markdown evaluation report."
    )

    gt_note = (
        str(ground_truth_count)
        if ground_truth_count
        else "Unknown — estimated from confidence distribution"
    )

    # Build per-image table if available
    per_image_section = ""
    if precomputed:
        import json as _json
        ctx_path = __import__("pathlib").Path(__file__).resolve().parent.parent / "session_context" / f"{session_id}.json"
        if ctx_path.exists():
            raw = _json.loads(ctx_path.read_text())
            per_img = raw.get("per_image_stats", [])
            if per_img:
                rows = "\n".join(
                    f"| {s['image_id']} | {s['match_count']} | {s['max_confidence']} | {s['mean_confidence']} | {s['min_confidence']} |"
                    for s in per_img
                )
                per_image_section = f"""
### PER-IMAGE CONFIDENCE BREAKDOWN:
| Image ID | Matches | Max Conf | Mean Conf | Min Conf |
|----------|---------|----------|-----------|----------|
{rows}
"""

    user_prompt = f"""### RETRIEVAL RESULTS (JSON):
{math_context}
{metrics_section}
{per_image_section}
**Ground Truth count in dataset:** {gt_note}
**Source feature:** {precomputed.get('source', 'unknown') if precomputed else 'unknown'}
**Query label:** {precomputed.get('query_label', 'unknown') if precomputed else 'unknown'}

Generate a comprehensive Evaluation Report that:
1. Uses the pre-computed metrics table above (verify and narrate each one)
2. Includes per-image confidence analysis using the per-image breakdown table
3. Identifies patterns in the confidence score distribution across images
4. Ends with a "Key Insights" section (3-5 actionable observations)

**Format:** Markdown with tables, bullet points, and clear section headers.
Keep it professional and concise.
"""

    response = await client.chat.completions.create(
        model=_OPENROUTER_MODEL,
        max_tokens=_OPENROUTER_MAX_TOKENS,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
    )
    return response.choices[0].message.content


async def vlm_chat(session_id: str, user_message: str) -> str:
    """
    General Q&A with the VLM, grounded in the stored search-context JSON
    and pre-computed metrics.
    """
    if not os.getenv("OPENROUTER_API_KEY"):
        return "VLM unavailable — set OPENROUTER_API_KEY in the backend environment."

    client = _get_client()
    math_context = load_search_context(session_id)
    precomputed  = load_metrics(session_id)

    metrics_summary = ""
    if precomputed and precomputed.get("metrics"):
        m = precomputed["metrics"]
        metrics_summary = (
            f"\n### PRE-COMPUTED METRICS:\n"
            f"K={m.get('k')}, Precision@K={m.get('precision_at_k')}, "
            f"Recall@K={m.get('recall_at_k')}, F1={m.get('f1')}, "
            f"mAP={m.get('map')}, NDCG@K={m.get('ndcg_at_k')}, "
            f"MRR={m.get('mrr')}, Silhouette={m.get('silhouette')}\n"
            f"Conf: mean={m.get('conf_mean')}, std={m.get('conf_std')}, "
            f"min={m.get('conf_min')}, max={m.get('conf_max')}, "
            f"high_conf_count={m.get('high_conf_count')}\n"
        )

    system_prompt = (
        "You are an expert geospatial intelligence analyst assistant. "
        "You have access to DINOv2 k-NN visual search results on satellite imagery "
        "including raw match data and pre-computed retrieval metrics. "
        "Answer questions concisely and accurately, referencing specific numbers "
        "from the context when relevant."
    )

    user_prompt = (
        f"### SEARCH CONTEXT (JSON):\n{math_context}"
        f"{metrics_summary}\n"
        f"### USER QUESTION:\n{user_message}"
    )

    response = await client.chat.completions.create(
        model=_OPENROUTER_MODEL,
        max_tokens=_OPENROUTER_MAX_TOKENS,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
    )
    return response.choices[0].message.content
